static const uint8_t CONFIG_CSI_SEND_MAC[] = {0x1a, 0x00, 0x00, 0x00, 0x00, 0x00};
#define MAX_CSI_BYTES 640
typedef struct {
    uint32_t seq;
    uint8_t mac[6];
    int8_t rssi;
    int8_t noise_floor;
    uint8_t channel;
    uint16_t len;
    bool first_word_invalid;
    uint8_t agc_gain;
    int8_t fft_gain;
    int8_t data[MAX_CSI_BYTES];
} csi_frame_t;

static QueueHandle_t csi_queue;
static uint32_t dropped_frames;

static void csi_print_task(void *arg)
{
    csi_frame_t frame;
    uint32_t samples = 0;
    while (xQueueReceive(csi_queue, &frame, portMAX_DELAY) == pdTRUE) {
        float compensate_gain = 1.0f;
        if (samples++ < 100) {
            esp_csi_gain_ctrl_record_rx_gain(frame.agc_gain, frame.fft_gain);
        } else {
            // ponytail: raw CSI during baseline warm-up; append gain metadata if mixing scales matters.
            (void)esp_csi_gain_ctrl_get_gain_compensation(&compensate_gain,
                                                           frame.agc_gain, frame.fft_gain);
        }
        ets_printf("CSI_DATA,%lu," MACSTR ",%d,%d,%d,%d,%d,\"[",
                   (unsigned long)frame.seq, MAC2STR(frame.mac), frame.rssi,
                   frame.noise_floor, frame.channel, frame.len, frame.first_word_invalid);
        for (int i = 0; i < frame.len; ++i) {
            ets_printf("%s%d", i == 0 ? "" : ",", (int16_t)(compensate_gain * frame.data[i]));
        }
        ets_printf("]\"\n");
        if (dropped_frames && samples % 100 == 0) {
            ets_printf("CSI_DROPPED,%" PRIu32 "\n", dropped_frames);
        }
    }
}

static void wifi_init()
{
    ESP_ERROR_CHECK(esp_event_loop_create_default());
    ESP_ERROR_CHECK(esp_netif_init());
    wifi_init_config_t cfg = WIFI_INIT_CONFIG_DEFAULT();
    ESP_ERROR_CHECK(esp_wifi_init(&cfg));
    ESP_ERROR_CHECK(esp_wifi_set_mode(WIFI_MODE_STA));
    ESP_ERROR_CHECK(esp_wifi_set_storage(WIFI_STORAGE_RAM));

#if CONFIG_IDF_TARGET_ESP32C5
    ESP_ERROR_CHECK(esp_wifi_start());
    esp_wifi_set_band_mode(CONFIG_WIFI_BAND_MODE);
    wifi_protocols_t protocols = {
        .ghz_2g = CONFIG_WIFI_2G_PROTOCOL,
        .ghz_5g = CONFIG_WIFI_5G_PROTOCOL
    };
    ESP_ERROR_CHECK(esp_wifi_set_protocols(ESP_IF_WIFI_STA, &protocols));
    wifi_bandwidths_t bandwidth = {
        .ghz_2g = CONFIG_WIFI_2G_BANDWIDTHS,
        .ghz_5g = CONFIG_WIFI_5G_BANDWIDTHS
    };
    ESP_ERROR_CHECK(esp_wifi_set_bandwidths(ESP_IF_WIFI_STA, &bandwidth));
#elif (CONFIG_IDF_TARGET_ESP32C6 && ESP_IDF_VERSION >= ESP_IDF_VERSION_VAL(5, 4, 0)) || CONFIG_IDF_TARGET_ESP32C61
    ESP_ERROR_CHECK(esp_wifi_start());
    esp_wifi_set_band_mode(CONFIG_WIFI_BAND_MODE);
    wifi_protocols_t protocols = {
        .ghz_2g = CONFIG_WIFI_2G_PROTOCOL,
    };
    ESP_ERROR_CHECK(esp_wifi_set_protocols(ESP_IF_WIFI_STA, &protocols));
    wifi_bandwidths_t bandwidth = {
        .ghz_2g = CONFIG_WIFI_2G_BANDWIDTHS,
    };
    ESP_ERROR_CHECK(esp_wifi_set_bandwidths(ESP_IF_WIFI_STA, &bandwidth));
#else
    ESP_ERROR_CHECK(esp_wifi_set_bandwidth(ESP_IF_WIFI_STA, CONFIG_WIFI_BANDWIDTH));
    ESP_ERROR_CHECK(esp_wifi_start());
#endif

    ESP_ERROR_CHECK(esp_wifi_set_ps(WIFI_PS_NONE));
#if CONFIG_IDF_TARGET_ESP32C5
    if ((CONFIG_WIFI_BAND_MODE == WIFI_BAND_MODE_2G_ONLY && CONFIG_WIFI_2G_BANDWIDTHS == WIFI_BW_HT20)
            || (CONFIG_WIFI_BAND_MODE == WIFI_BAND_MODE_5G_ONLY && CONFIG_WIFI_5G_BANDWIDTHS == WIFI_BW_HT20)) {
        ESP_ERROR_CHECK(esp_wifi_set_channel(CONFIG_LESS_INTERFERENCE_CHANNEL, WIFI_SECOND_CHAN_NONE));
    } else {
        ESP_ERROR_CHECK(esp_wifi_set_channel(CONFIG_LESS_INTERFERENCE_CHANNEL, WIFI_SECOND_CHAN_BELOW));
    }
#elif (CONFIG_IDF_TARGET_ESP32C6 && ESP_IDF_VERSION >= ESP_IDF_VERSION_VAL(5, 4, 0)) || CONFIG_IDF_TARGET_ESP32C61
    if (CONFIG_WIFI_BAND_MODE == WIFI_BAND_MODE_2G_ONLY && CONFIG_WIFI_2G_BANDWIDTHS == WIFI_BW_HT20) {
        ESP_ERROR_CHECK(esp_wifi_set_channel(CONFIG_LESS_INTERFERENCE_CHANNEL, WIFI_SECOND_CHAN_NONE));
    } else {
        ESP_ERROR_CHECK(esp_wifi_set_channel(CONFIG_LESS_INTERFERENCE_CHANNEL, WIFI_SECOND_CHAN_BELOW));
    }
#else
    if (CONFIG_WIFI_BANDWIDTH == WIFI_BW_HT20) {
        ESP_ERROR_CHECK(esp_wifi_set_channel(CONFIG_LESS_INTERFERENCE_CHANNEL, WIFI_SECOND_CHAN_NONE));
    } else {
        ESP_ERROR_CHECK(esp_wifi_set_channel(CONFIG_LESS_INTERFERENCE_CHANNEL, WIFI_SECOND_CHAN_BELOW));
    }
#endif

}

static void wifi_esp_now_init(esp_now_peer_info_t peer)
{
    ESP_ERROR_CHECK(esp_now_init());
    ESP_ERROR_CHECK(esp_now_set_pmk((uint8_t *)"pmk1234567890123"));
    esp_now_rate_config_t rate_config = {
        .phymode = CONFIG_ESP_NOW_PHYMODE,
        .rate = CONFIG_ESP_NOW_RATE,//  WIFI_PHY_RATE_MCS0_LGI,
        .ersu = false,
        .dcm = false
    };
    ESP_ERROR_CHECK(esp_now_add_peer(&peer));
    ESP_ERROR_CHECK(esp_now_set_peer_rate_config(peer.peer_addr, &rate_config));

}

static void wifi_csi_rx_cb(void *ctx, wifi_csi_info_t *info)
{
    if (!info || !info->buf || memcmp(info->mac, CONFIG_CSI_SEND_MAC, 6)) {
        return;
    }
    if (info->len > MAX_CSI_BYTES) {
        ++dropped_frames;
        return;
    }
    static uint32_t s_count;
    csi_frame_t frame = {
        .seq = s_count++,
        .rssi = info->rx_ctrl.rssi,
        .noise_floor = info->rx_ctrl.noise_floor,
        .channel = info->rx_ctrl.channel,
        .len = info->len,
        .first_word_invalid = info->first_word_invalid,
    };
    if (info->payload && info->payload_len >= 19) {
        memcpy(&frame.seq, info->payload + 15, sizeof(frame.seq));
    }
    memcpy(frame.mac, info->mac, sizeof(frame.mac));
    esp_csi_gain_ctrl_get_rx_gain(&info->rx_ctrl, &frame.agc_gain, &frame.fft_gain);
    memcpy(frame.data, info->buf, frame.len);
    if (xQueueSend(csi_queue, &frame, 0) != pdTRUE) {
        ++dropped_frames;
    }
}

